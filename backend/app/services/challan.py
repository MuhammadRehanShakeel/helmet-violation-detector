"""
challan.py - Creates the PDF e-challan (traffic ticket) for an approved violation.

The PDF has: challan number, date, place, number plate, the offence and fine,
the evidence photo, the plate photo, and a QR code. The QR code holds a
random verify code: anyone can scan it to check the challan is real
(GET /challans/verify/{code}), but the code cannot be guessed.

Used by: app/routes/violation_routes.py
"""
import os
import secrets
from datetime import datetime

from reportlab.graphics import renderPDF
from reportlab.graphics.barcode import qr
from reportlab.graphics.shapes import Drawing
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

from app import config


def new_codes(violation_id: int):
    """Challan number people can read + a secret verify code for the QR."""
    challan_no = f"RG-{datetime.now():%Y%m%d}-{violation_id:05d}"
    return challan_no, secrets.token_urlsafe(18)


def _image(c, path, x, y, max_w, max_h):
    if not path or not os.path.exists(path):
        return
    img = ImageReader(path)
    w, h = img.getSize()
    scale = min(max_w / w, max_h / h)
    c.drawImage(img, x, y + (max_h - h * scale), w * scale, h * scale)


def make_pdf(path, info: dict):
    """
    info keys: challan_no, verify_code, issued_at, plate, violation_label, fine, camera, location,
               detected_at, officer, evidence_path, plate_path, confidence
    """
    c = canvas.Canvas(path, pagesize=A4)
    width, height = A4
    purple = colors.HexColor("#1f2a44")

    c.setFillColor(purple)
    c.rect(0, height - 32 * mm, width, 32 * mm, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 20)
    c.drawString(15 * mm, height - 15 * mm, "E-CHALLAN  |  Traffic Violation Notice")
    c.setFont("Helvetica", 10)
    c.drawString(15 * mm, height - 23 * mm, config.CHALLAN_AUTHORITY)
    c.drawRightString(width - 15 * mm, height - 15 * mm, info["challan_no"])

    rows = [
        ("Vehicle number", info["plate"] or "Not readable - see photo"),
        ("Offence", info["violation_label"]),
        ("Fine", f"Rs {info['fine']:,}"),
        ("Camera / place", f"{info['camera']} - {info['location']}"),
        ("Detected at", info["detected_at"]),
        ("Issued at", info["issued_at"]),
        ("Reviewed and issued by", info["officer"]),
        ("AI confidence", f"{info['confidence'] * 100:.0f}% (checked by a human officer)"),
    ]
    y = height - 45 * mm
    for label, value in rows:
        c.setFillColor(colors.HexColor("#6b7280"))
        c.setFont("Helvetica", 10)
        c.drawString(15 * mm, y, label)
        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 11)
        c.drawString(65 * mm, y, str(value))
        y -= 8 * mm

    code = qr.QrCodeWidget(f"{config.PUBLIC_BASE_URL}/verify/{info['verify_code']}")
    b = code.getBounds()
    size = 38 * mm
    drawing = Drawing(size, size, transform=[size / (b[2] - b[0]), 0, 0, size / (b[3] - b[1]), 0, 0])
    drawing.add(code)
    renderPDF.draw(drawing, c, width - 15 * mm - size, height - 45 * mm - size + 6 * mm)
    c.setFont("Helvetica", 8)
    c.drawCentredString(width - 15 * mm - size / 2, height - 45 * mm - size + 3 * mm, "Scan to verify")

    c.setFont("Helvetica-Bold", 12)
    c.drawString(15 * mm, y - 4 * mm, "Evidence")
    _image(c, info.get("evidence_path"), 15 * mm, y - 120 * mm, width - 30 * mm, 110 * mm)
    if info.get("plate_path"):
        c.drawString(15 * mm, y - 132 * mm, "Number plate")
        _image(c, info["plate_path"], 15 * mm, y - 170 * mm, 70 * mm, 34 * mm)

    c.setFont("Helvetica", 8)
    c.setFillColor(colors.HexColor("#6b7280"))
    c.drawString(15 * mm, 12 * mm, "Demo e-challan generated by RoadGuard (portfolio project). Not an official government document.")
    c.showPage()
    c.save()
